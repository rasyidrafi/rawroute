import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"

test("providers use a list page and a dynamic detail page", () => {
  const routes = readFileSync(new URL("../../packages/gateway-ai/src/web/views.tsx", import.meta.url), "utf8")
  const list = readFileSync(new URL("../../packages/gateway-ai/src/web/components/providers-view.tsx", import.meta.url), "utf8")
  const detail = readFileSync(new URL("../../packages/gateway-ai/src/web/components/provider-detail-view.tsx", import.meta.url), "utf8")
  const loginDialog = readFileSync(new URL("../../packages/gateway-ai/src/web/components/codex-login-dialog.tsx", import.meta.url), "utf8")

  expect(routes).toContain("<ProviderPage />")
  expect(routes).toContain('providerId="codex"')
  expect(list).toContain("providerPagePath(provider.id)")
  expect(detail).toContain('buttonLabel="Delete provider"')
  expect(detail).toContain("Expose upstream models behind your provider prefix.")
  expect(detail).toContain('isOAuthProvider ? "Accounts" : "API keys"')
  expect(detail).not.toContain('apiKey.credentialKind === "codex-oauth" ? null')
  expect(detail).toContain("moveProviderApiKey(index, -1)")
  expect(detail).toContain("moveProviderApiKey(index, 1)")
  expect(detail).toContain("deleteModel")
  expect(detail.indexOf("<CodexAutoRedeemCard accounts={apiKeys} />")).toBeLessThan(detail.indexOf("<ProviderCredentialsCard"))
  expect(detail).toContain("Redeem eligible credits within 1 hour of expiry.")
  expect(detail).toContain("Before credits expire")
  expect(detail).toContain("When weekly quota runs out")
  expect(detail).not.toContain("On by default.")
  expect(detail).not.toContain("Off by default.")
  expect(detail).not.toContain("Request ID:")
  expect(detail).toContain("weeklyExhaustionEnabled: false")
  expect(detail).toContain('aria-label="Also redeem when weekly quota is exhausted"')
  expect(detail).toContain("<CodexLoginDialog login={login} />")
  expect(detail.match(/nativeButton=\{false\}/g)).toHaveLength(1)
  expect(loginDialog.match(/nativeButton=\{false\}/g)).toHaveLength(1)
  expect(list.match(/nativeButton=\{false\}/g)).toHaveLength(2)
})
